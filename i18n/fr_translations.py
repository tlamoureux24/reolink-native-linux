    path = sys.argv[1] if len(sys.argv) > 1 else "i18n/reolink-client_fr.ts"
    missing = apply(path)
    if missing:
        print("untranslated:", *missing, sep="\n  ")
        sys.exit(1)
    print("all strings translated")
