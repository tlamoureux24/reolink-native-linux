def apply(ts_path):
    tree = ET.parse(ts_path)
    root = tree.getroot()
    missing = []
    for msg in root.iter("message"):
        src = msg.find("source").text or ""
        plural = msg.get("numerus") == "yes"
        key = ("P|" + src) if plural else src
        tr = msg.find("translation")
        value = FR.get(key)
        if value is None:
            missing.append(key)
            continue
        for child in list(tr):
            tr.remove(child)
        tr.attrib.pop("type", None)
        if plural:
            tr.text = None
            for form in value:
                ET.SubElement(tr, "numerusform").text = form
        else:
            tr.text = value
    tree.write(ts_path, encoding="utf-8", xml_declaration=True)
    return missing


